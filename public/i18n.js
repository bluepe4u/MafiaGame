const LANG_KEY = 'mafia.lang';
let lang = (() => {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved && DICT[saved]) return saved;
  } catch {}
  return (navigator.language || '').toLowerCase().startsWith('ru') ? 'ru' : 'en';
})();

function setLang(l) {
  if (!DICT[l]) return;
  lang = l;
  try { localStorage.setItem(LANG_KEY, l); } catch {}
  document.documentElement.lang = l;
}

// Family mode swaps in gentler texts: a key with a "<key>.family" version uses that instead.
let i18nVariant = null;
function t(key, params = {}) {
  const alt = i18nVariant && (DICT[lang][`${key}.${i18nVariant}`] ?? DICT.en[`${key}.${i18nVariant}`]);
  const v = alt ?? DICT[lang][key] ?? DICT.en[key];
  if (v === undefined) return key;
  if (typeof v === 'function') return v(params);
  return v.replace(/\{(\w+)\}/g, (m, k) => (k in params ? params[k] : m));
}

function tally(p) {
  const parts = p.tally.map(([name, c]) => `${name} ${c}`);
  if (p.skips) parts.push(t('log.tallySkip', { n: p.skips }));
  return parts.join(', ') || t('log.noVotes');
}

// Fill static markup: data-i18n (text), data-i18n-placeholder
function applyStaticTranslations(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-placeholder]')) el.placeholder = t(el.dataset.i18nPlaceholder);
}

